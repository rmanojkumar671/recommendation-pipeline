"""Export small, human-readable samples of every pipeline output to data/samples/.

The full datasets are regenerated by `python run_pipeline.py` and are not
committed (MovieLens licence + reproducibility). These samples (first N rows
of each table, plus the metadata files) let a reader see what each stage
produces without running anything.

    python -m src.utils.export_samples          # 20 rows per table
    python -m src.utils.export_samples --rows 50
"""
from __future__ import annotations

import argparse
import shutil

import pandas as pd

from src.utils.common import load_config

TABLES = [
    # (stage, source path relative to paths key, sample file name)
    ("1_ingestion", "raw", "users.csv"),
    ("1_ingestion", "raw", "items.csv"),
    ("1_ingestion", "raw", "interactions.csv"),
    ("2_validation", "processed", "validated_interactions.parquet"),
    ("3_preparation", "processed", "users.parquet"),
    ("3_preparation", "processed", "items.parquet"),
    ("3_preparation", "processed", "train.parquet"),
    ("3_preparation", "processed", "test.parquet"),
    ("4_transformation", "processed", "user_activity_summary.parquet"),
    ("4_transformation", "processed", "item_popularity.parquet"),
    ("4_transformation", "processed", "genre_summary.parquet"),
    ("5_features", "features", "user_features.parquet"),
    ("5_features", "features", "item_features.parquet"),
    ("5_features", "features", "interaction_features.parquet"),
]
METADATA = [
    ("1_ingestion", "raw", "ingestion_manifest.json"),
    ("3_preparation", "processed", "split_metadata.json"),
    ("4_transformation", "processed", "transformation_metadata.json"),
    ("5_features", "features", "feature_metadata.json"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=20)
    ap.add_argument("--config", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    out = cfg["paths"]["raw"].parent / "samples"
    out.mkdir(parents=True, exist_ok=True)

    index = []
    for stage, key, name in TABLES:
        src = cfg["paths"][key] / name
        df = pd.read_csv(src, dtype=str, keep_default_na=False) if name.endswith(".csv") else pd.read_parquet(src)
        full_rows, full_cols = len(df), df.shape[1]
        (out / stage).mkdir(exist_ok=True)
        dest = out / stage / (name.rsplit(".", 1)[0] + "_sample.csv")
        df.head(args.rows).to_csv(dest, index=False)
        index.append(f"| {stage} | `{dest.relative_to(out).as_posix()}` | `{key}/{name}` | {full_rows:,} | {full_cols} |")
    for stage, key, name in METADATA:
        (out / stage).mkdir(exist_ok=True)
        shutil.copy(cfg["paths"][key] / name, out / stage / name)
        index.append(f"| {stage} | `{stage}/{name}` | `{key}/{name}` | metadata | - |")

    readme = [
        "# Data samples",
        "",
        f"The first {args.rows} rows of every table the pipeline produces, plus the metadata files of each stage. "
        "The full data is **not committed**: the MovieLens licence does not allow redistribution, and every derived "
        "file is regenerated by `python run_pipeline.py` (about 1 minute). Regenerate these samples with "
        "`python -m src.utils.export_samples`.",
        "",
        "Note: `1_ingestion/interactions_sample.csv` is the raw file *after* the documented noise injection, "
        "so it may contain corrupted rows; `data/errors/` shows what validation quarantined.",
        "",
        "| Stage | Sample file | Full output | Full rows | Columns |",
        "|---|---|---|---|---|",
        *index,
        "",
    ]
    (out / "README.md").write_text("\n".join(readme), encoding="utf-8")
    print(f"Wrote samples to {out}")


if __name__ == "__main__":
    main()
